-- Opening stock, step 5 (docs/plans/2026-11-18-opening-stock.md §3.2, §5 step 5): the two tables of the carico, the audit values and the purge list.
--
--   public.stock_opening       one row per booked operation (one location, one date). Its id is the ref_id of the operation's `opening` movements. Append-only by trigger, as the
--                              ledger: a correction is a reversal (step 9), never an edit. The reversed state is not stored; it is derived from the ledger (a row of the operation has
--                              a mirror). request_id is the idempotency key of the confirm (a double tap books once); line_count is shown in the history.
--   public.opening_draft_line  the draft of the carico, shared by the owner's devices (spec §7.8). NOT ledger: rows are updated and deleted freely by the draft procedures of
--                              step 6, and the confirm of step 7 deletes the rows it books. The id is generated by the client, so a PUT is an idempotent upsert. One row per
--                              ingredient and location (lead ruling on Q3: no "Riga separata").
--
-- Both tables carry tenant_id with composite foreign keys, RLS on, one select policy for the owner and the admin of the tenant, select for service_role (read-only, as on
-- invoice_vat_summary), and no insert, update, delete or truncate grant to any API role (service_role included): rows are written only by the security-definer procedures of steps 6, 7 and 9.
--
-- audit_event: entity type 'stock_opening' and actions 'stock.opening_posted' and 'stock.opening_reversed' are added to the two checks; each check is re-created as the union of
-- every value on main (entity types of 20261124100200, actions of 20261204100300) plus these.
-- Purge list (ADR-018): app.demo_purge_tables() is the list of 20261204100200 with 'opening_draft_line' and 'stock_opening' right after 'raw_lot' (61 names). Both point at locations,
-- ingredients and users, which are deleted later; nothing points at them. app.tenant_has_operational_data reads the list and is not replaced: a tenant with a carico has data.

create table public.stock_opening (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenant (id),
  location_id uuid not null,
  effective_on date not null,
  request_id uuid not null,
  line_count integer not null,
  created_at timestamptz not null default now(),
  created_by uuid not null,
  constraint stock_opening_tenant_id_id_uq unique (tenant_id, id),
  constraint stock_opening_request_uq unique (tenant_id, request_id),
  constraint stock_opening_line_count_ck check (line_count between 1 and 200),
  constraint stock_opening_location_fk foreign key (tenant_id, location_id) references public.location (tenant_id, id),
  constraint stock_opening_created_by_fk foreign key (tenant_id, created_by) references public.app_user (tenant_id, id)
);
create index stock_opening_location_idx on public.stock_opening (tenant_id, location_id, created_at desc);

comment on table public.stock_opening is
  'Opening stock (carico iniziale): one row per booked operation at one location. Its id is the ref_id of the operation''s opening movements. Append-only; corrected by reversal.';
comment on column public.stock_opening.effective_on is 'The "Data del carico" chosen by the owner; the movements carry the same date.';

create table public.opening_draft_line (
  id uuid primary key,
  tenant_id uuid not null references public.tenant (id),
  location_id uuid not null,
  ingredient_id uuid not null,
  qty numeric(12, 4) not null,
  unit_cost numeric(12, 4) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null,
  updated_by uuid not null,
  constraint opening_draft_line_tenant_id_id_uq unique (tenant_id, id),
  constraint opening_draft_line_ingredient_uq unique (tenant_id, location_id, ingredient_id),
  constraint opening_draft_line_qty_ck check (qty > 0 and qty <= 100000),
  constraint opening_draft_line_unit_cost_ck check (unit_cost >= 0 and unit_cost <= 100000),
  constraint opening_draft_line_location_fk foreign key (tenant_id, location_id) references public.location (tenant_id, id),
  constraint opening_draft_line_ingredient_fk foreign key (tenant_id, ingredient_id) references public.ingredient (tenant_id, id),
  constraint opening_draft_line_created_by_fk foreign key (tenant_id, created_by) references public.app_user (tenant_id, id),
  constraint opening_draft_line_updated_by_fk foreign key (tenant_id, updated_by) references public.app_user (tenant_id, id)
);

comment on table public.opening_draft_line is
  'The draft of the opening stock (carico iniziale), shared by the owner''s devices. Not ledger: rows are edited and deleted freely by the draft procedures; the confirm deletes what it books.';
comment on column public.opening_draft_line.unit_cost is 'EUR per base unit, net of VAT, as typed by the owner.';

alter table public.stock_opening enable row level security;
alter table public.opening_draft_line enable row level security;

revoke all on public.stock_opening, public.opening_draft_line from anon, authenticated;
revoke insert, update, delete, truncate on public.stock_opening, public.opening_draft_line from service_role;
grant select on public.stock_opening, public.opening_draft_line to authenticated, service_role;

create policy stock_opening_select on public.stock_opening
  for select to authenticated
  using (tenant_id = (select app.tenant_id()) and (select app.role()) in ('owner', 'admin'));
create policy opening_draft_line_select on public.opening_draft_line
  for select to authenticated
  using (tenant_id = (select app.tenant_id()) and (select app.role()) in ('owner', 'admin'));

create trigger stock_opening_append_only
  before update or delete on public.stock_opening
  for each row execute function app.append_only();
create trigger stock_opening_no_truncate
  before truncate on public.stock_opening
  for each statement execute function app.append_only_truncate();

