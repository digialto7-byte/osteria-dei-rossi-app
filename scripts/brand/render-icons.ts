// Renders the Costì PNGs from the SVG slots in public/brand/costi/ (docs/plans/2026-11-13-costi-product-brand.md §3.6), with the
// Chromium of @playwright/test (already a devDependency; no other tool). It writes the six PNGs, renders.json (each PNG's source
// slot, size and the sha256 of the SVG it was made from) and README.md (slots, delivery rules, checksums).
//   npx tsx scripts/brand/render-icons.ts
// The swap to the founder's logo files is: replace the SVGs, run this, commit the SVGs, the PNGs, renders.json and README.md.
// tests/config/costi-brand-assets.test.ts fails if an SVG was replaced without re-rendering.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { format, resolveConfig } from "prettier";
import { COSTI_PNGS, COSTI_SVGS } from "../../src/lib/brand/costi-assets";

const DIR = new URL("../../public/brand/costi/", import.meta.url).pathname;
const sha256 = (data: Buffer | string) => createHash("sha256").update(data).digest("hex");
const fileOf = (url: string) => url.slice(url.lastIndexOf("/") + 1);

async function render(svg: Buffer, size: number): Promise<Buffer> {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({
      viewport: { width: size, height: size },
      deviceScaleFactor: 1,
    });
    const src = `data:image/svg+xml;base64,${svg.toString("base64")}`;
    await page.setContent(
      `<!doctype html><html><body style="margin:0;background:transparent"><img id="i" alt="" src="${src}" style="display:block;width:${size}px;height:${size}px"></body></html>`,
    );
    await page.evaluate(() => (document.getElementById("i") as HTMLImageElement).decode());
    return await page.screenshot({
      type: "png",
      omitBackground: true,
      clip: { x: 0, y: 0, width: size, height: size },
    });
  } finally {
    await browser.close();
  }
}

